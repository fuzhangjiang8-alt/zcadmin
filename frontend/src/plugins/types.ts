// =============================================================================
// 前端插件契约
//
// 一个前端插件 = 一个 id + 一组路由。路由的 path 是相对布局的（不带前导 /），
// 与后端菜单里的 path 去掉前缀后一一对应。
//
// 为什么先做"注册表"而不是 pnpm 包：
//   独立包需要处理依赖版本、构建产物、类型共享，成本高；
//   注册表已经实现"新增插件只改一个目录 + 一行注册"的核心目标，
//   等真的需要独立发版/懒加载时再拆包，迁移成本很低。
// =============================================================================

import type { RouteRecordRaw } from 'vue-router';

/** 前端插件定义。 */
export interface FrontendPlugin {
  /** 插件 id，需与后端插件 id 一致（crm / demo / ...）。 */
  id: string;
  /** 该插件贡献的路由（挂在 LayoutView 下）。 */
  routes: RouteRecordRaw[];
}
